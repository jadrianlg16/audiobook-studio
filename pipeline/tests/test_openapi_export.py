"""docs/studio-openapi.json — the studio's OpenAPI, exported for the UI's types.

The Director's Desk generates its API types from that file and fails its build
on drift, so a stale file is a UI typed against an API that no longer exists.
It is regenerated by ``scripts/export_studio_openapi.py`` (Amendment v1.3 in
docs/STUDIO-API.md); these tests fail when someone changes a route or a wire
model and forgets to.
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
import typing
from pathlib import Path

import pytest
from fastapi import Response
from fastapi.datastructures import DefaultPlaceholder
from fastapi.routing import APIRoute
from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "export_studio_openapi.py"
EXPORT = ROOT / "docs" / "studio-openapi.json"


def _exporter():
    spec = importlib.util.spec_from_file_location("export_studio_openapi", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_the_committed_export_matches_a_fresh_one(tmp_path, monkeypatch):
    # Importing the app builds it, and building it creates the books folder.
    monkeypatch.setenv("AUDIOBOOK_OUTPUT", str(tmp_path / "output"))
    exporter = _exporter()
    recorded = exporter.recorded_versions(EXPORT)
    if recorded != exporter.versions():
        # Another FastAPI/Pydantic words the same API differently; only the
        # exporting environment can tell drift from noise.
        pytest.skip(f"export made with {recorded}, this machine has {exporter.versions()}")
    problem = exporter.check(EXPORT)
    assert problem is None, problem

    # Paths as the service serves them: nginx strips /studio before proxying.
    paths = json.loads(EXPORT.read_text(encoding="utf-8"))["paths"]
    assert paths and all(p == "/" or p.startswith("/api/") for p in paths), sorted(paths)


def test_check_mode_exits_1_on_a_stale_file_and_says_how_to_fix_it(tmp_path):
    fresh_copy = tmp_path / "fresh.json"
    wrote = subprocess.run(
        [sys.executable, str(SCRIPT), "--out", str(fresh_copy)],
        capture_output=True, text=True, encoding="utf-8",
    )
    assert wrote.returncode == 0, wrote.stdout + wrote.stderr
    fresh = subprocess.run(
        [sys.executable, str(SCRIPT), "--check", "--out", str(fresh_copy)],
        capture_output=True, text=True, encoding="utf-8",
    )
    assert fresh.returncode == 0, fresh.stdout + fresh.stderr

    stale = tmp_path / "studio-openapi.json"
    stale.write_text('{"openapi": "3.1.0", "paths": {}}\n', encoding="utf-8")
    result = subprocess.run(
        [sys.executable, str(SCRIPT), "--check", "--out", str(stale)],
        capture_output=True, text=True, encoding="utf-8",
    )
    assert result.returncode == 1, result.stdout + result.stderr
    assert "python scripts/export_studio_openapi.py" in result.stderr
    assert stale.read_text(encoding="utf-8") == '{"openapi": "3.1.0", "paths": {}}\n', "--check wrote"


def _is_a_model(tp) -> bool:
    if isinstance(tp, type) and issubclass(tp, BaseModel):
        return True
    return typing.get_origin(tp) is list and _is_a_model(typing.get_args(tp)[0])


def _returns_a_response(endpoint) -> bool:
    returned = typing.get_type_hints(endpoint).get("return")
    return isinstance(returned, type) and issubclass(returned, Response)


def test_every_json_route_declares_its_response_model(tmp_path, monkeypatch):
    """An undeclared JSON body exports as a bare object and types as ``unknown``
    in the UI — six routes were like that until v1.3. A route that returns a
    Response itself (a WAV, the SSE stream, a 204) has no JSON body to type."""
    monkeypatch.setenv("AUDIOBOOK_OUTPUT", str(tmp_path / "output"))
    from pipeline.webapp import app

    untyped = []
    for route in app.routes:
        if not isinstance(route, APIRoute) or not route.include_in_schema:
            continue
        if not isinstance(route.response_class, DefaultPlaceholder):
            continue  # the HTML index page, the line WAV, the job event stream
        if route.response_model is None and _returns_a_response(route.endpoint):
            continue
        if not _is_a_model(route.response_model):
            untyped.append(f"{'/'.join(sorted(route.methods))} {route.path} -> {route.response_model!r}")
    assert untyped == [], "declare a response_model (see docs/STUDIO-API.md v1.3):\n" + "\n".join(untyped)


# ---- Amendment v1.4: the export describes the wire exactly --------------------


def _export() -> dict:
    return json.loads(EXPORT.read_text(encoding="utf-8"))


def _components_in_responses(schema: dict) -> set[str]:
    """Every component a response body can reach, following ``$ref``s."""
    components = schema["components"]["schemas"]
    seen: set[str] = set()

    def walk(node) -> None:
        if isinstance(node, dict):
            ref = node.get("$ref")
            if isinstance(ref, str):
                name = ref.rsplit("/", 1)[-1]
                if name not in seen:
                    seen.add(name)
                    walk(components[name])
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    for item in schema["paths"].values():
        for operation in item.values():
            for response in operation.get("responses", {}).values():
                walk(response.get("content", {}))
    return seen


def test_response_schemas_require_every_field_the_wire_always_sends():
    """A field with a default is always serialized, so a response schema that
    calls it optional types a never-missing field as ``| undefined`` in the UI."""
    schema = _export()
    components = schema["components"]["schemas"]
    reached = _components_in_responses(schema)
    assert {"Script", "Line", "Render", "PassScene", "Settings", "ExportFile"} <= reached
    loose = []
    for name in sorted(reached):
        component = components[name]
        optional = set(component.get("properties", {})) - set(component.get("required", []))
        if optional:
            loose.append(f"{name}: {sorted(optional)}")
    assert loose == [], "response fields exported as optional:\n" + "\n".join(loose)


def test_the_export_declares_errors_raw_bodies_and_non_json_responses():
    schema = _export()
    components = schema["components"]["schemas"]
    paths = schema["paths"]

    # One error body, everywhere; FastAPI's 422 list never reaches the wire.
    assert "HTTPValidationError" not in components
    assert components["ErrorDetail"]["required"] == ["detail"]
    error = {"$ref": "#/components/schemas/ErrorDetail"}
    undeclared = [
        f"{method.upper()} {path}"
        for path, item in paths.items()
        if path.startswith("/api/")
        for method, operation in item.items()
        if operation["responses"].get("default", {}).get("content", {}).get("application/json", {}).get("schema")
        != error
    ]
    assert undeclared == []

    # The two bodies parsed by hand are named, with every field the parser knows.
    from pipeline.studio.models import CastPatchEntry, LinePatch

    def body(path, method):
        return paths[path][method]["requestBody"]["content"]["application/json"]["schema"]

    assert body("/api/books/{slug}/lines/{line_id}", "patch") == {"$ref": "#/components/schemas/LinePatch"}
    assert body("/api/books/{slug}/cast", "patch") == {
        "type": "array",
        "items": {"$ref": "#/components/schemas/CastPatchEntry"},
    }
    assert set(components["LinePatch"]["properties"]) == set(LinePatch.model_fields)
    assert set(components["CastPatchEntry"]["properties"]) == set(CastPatchEntry.model_fields)

    # Not JSON, and not advertised as JSON.
    audio = paths["/api/books/{slug}/lines/{line_id}/audio"]["get"]["responses"]["200"]["content"]
    events = paths["/api/jobs/{job_id}/events"]["get"]["responses"]["200"]["content"]
    assert list(audio) == ["audio/wav"]
    assert list(events) == ["text/event-stream"]
