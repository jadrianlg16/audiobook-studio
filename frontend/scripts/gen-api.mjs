/**
 * Generate src/studio/api/schema.gen.ts from the studio's exported OpenAPI
 * (docs/studio-openapi.json, written by scripts/export_studio_openapi.py).
 *
 *   node scripts/gen-api.mjs           write it                (npm run gen:api)
 *   node scripts/gen-api.mjs --check   exit 1 if it is stale   (npm run gen:api:check)
 *
 * --check regenerates in memory and compares, so `npm run check` fails when the
 * export changed and nobody regenerated — and never rewrites anything.
 *
 * `defaultNonNullable: false`: openapi-typescript would otherwise make every
 * property with a `default` required, which is wrong for request bodies (a
 * `LinePatch` with every field required). Response schemas need no help: the
 * studio marks every always-sent field `required` (STUDIO-API.md, v1.4).
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";
import * as prettier from "prettier";

const SOURCE = new URL("../../docs/studio-openapi.json", import.meta.url);
const TARGET = fileURLToPath(new URL("../src/studio/api/schema.gen.ts", import.meta.url));

const HEADER = `/**
 * GENERATED by \`npm run gen:api\` from docs/studio-openapi.json. Do not edit.
 *
 * After changing a studio route or wire model: \`python scripts/export_studio_openapi.py\`
 * at the repo root, then \`npm run gen:api\` here. src/studio/api/contract.ts checks the
 * hand-written types in types.ts against this file.
 */

`;

async function generate() {
  const ast = await openapiTS(SOURCE, { defaultNonNullable: false, silent: true });
  const config = (await prettier.resolveConfig(TARGET)) ?? {};
  return prettier.format(HEADER + astToString(ast), { ...config, filepath: TARGET });
}

const fresh = await generate();

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = (await readFile(TARGET, "utf8")).replace(/\r\n/g, "\n");
  } catch {
    // missing: stale by definition
  }
  if (current !== fresh) {
    console.error(
      "src/studio/api/schema.gen.ts is stale: docs/studio-openapi.json changed since it was " +
        "generated. Run `npm run gen:api` and commit the result.",
    );
    process.exit(1);
  }
  console.log("schema.gen.ts is fresh");
} else {
  await writeFile(TARGET, fresh);
  console.log(`wrote ${TARGET}`);
}
